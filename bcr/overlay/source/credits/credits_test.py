"""Check generated notices retain every shipped dependency's actual license."""

import html
import json
from pathlib import Path
import sys
import unittest

PAGE, INVENTORY = map(Path, sys.argv[1:3])
FILES = dict(zip(sys.argv[3::2], map(Path, sys.argv[4::2])))
del sys.argv[1:]


class CreditsTest(unittest.TestCase):
    def test_shipped_license_texts_names_and_urls_survive_html_generation(self):
        page = PAGE.read_bytes().decode("utf-8")
        self.assertTrue(page.startswith("<!-- Generated by licenses.py; do not edit. -->"))
        self.assertNotIn("{{entries}}", page)
        self.assertNotIn("{{reciprocal-license-statement}}", page)
        text = html.unescape(page)
        self.assertIn(FILES["LICENSE"].read_bytes().decode("utf-8", errors="replace"), text)
        shipped = [entry for entry in json.loads(INVENTORY.read_text())["metadata"] if entry["shipped"] != "no"]
        self.assertGreater(len(shipped), 400)
        for entry in shipped:
            with self.subTest(dependency=entry["name"], directory=entry["directory"]):
                self.assertIn(entry["name"], text)
                self.assertIn(entry["url"], text)
                self.assertTrue(entry["licenses"])
                for path in entry["licenses"]:
                    self.assertIn(FILES[path].read_bytes().decode("utf-8", errors="replace"), text)


if __name__ == "__main__":
    unittest.main()
