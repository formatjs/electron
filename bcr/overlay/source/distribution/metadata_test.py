"""Check distribution version and verbatim upstream notices."""

from pathlib import Path
import sys
import unittest

VERSION, LICENSE, ORIGINAL_LICENSE, CREDITS, ORIGINAL_CREDITS = map(Path, sys.argv[1:])
del sys.argv[1:]


class DistributionMetadataTest(unittest.TestCase):
    def test_release_identity_and_notice_bytes(self):
        self.assertEqual(VERSION.read_bytes(), b"39.0.0")
        self.assertEqual(LICENSE.read_bytes(), ORIGINAL_LICENSE.read_bytes())
        self.assertEqual(CREDITS.read_bytes(), ORIGINAL_CREDITS.read_bytes())
        self.assertTrue(CREDITS.read_bytes().startswith(b"<!-- Generated by licenses.py; do not edit. -->"))


if __name__ == "__main__":
    unittest.main()
